import assert from "node:assert/strict";
import { readFile, mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { chromium, expect } from "@playwright/test";

const root = fileURLToPath(new URL(".", import.meta.url));
const definition = async name => JSON.parse(await readFile(new URL(`../config/dc-ups/DSP/${name}.json`, import.meta.url), "utf8"));
const processDefinition = await definition("process"), forwardDefinition = await definition("transmit");
const board = { code: "DSP", name: "DSP 功率板", point_storage: "native", point_groups: [{ code: "LOCAL", name: "DSP 内部数据" }], point_endpoints: [{ code: "UPP_SERVICE", name: "UPP 对外接口", protocol: "UPP" }] };
const config = { version: 2, board_types: [{ code: "UPM", name: "UPM 控制板" }, board], root: { type: "UPM", quantity: 1 }, mounts: [{ parent: "UPM", child: "DSP", quantity: 8, connections: [{ protocol: "UPP", transport: "CAN" }] }] };
const point = { id: 1, board_key: "DSP", group_key: "LOCAL", name: "母线电压", enum_name: "BUS_VOLTAGE", internal_type: "U16", element_count: 1, byte_length: 2, sig_id: null };
const graph = { revision: 1, project_config: config, process_points: [point], transmit_points: [] };
const project = { id: 1, key: "dc-ups", name: "DC-UPS", revision: 1, role: "engineer" };
const catalog = [{ board_key: "DSP", board_name: "DSP 功率板", endpoints: [{ endpoint_key: "UPP_SERVICE", name: "UPP 对外接口", protocol: "UPP" }] }];
const permissions = { role: "admin", edit_scope: "all", grants: [], can_edit: true, can_manage_project: true, catalog };
const user = { id: 1, username: "test-admin", display_name: "测试管理员", is_admin: true, active: true };
const validation = { errors: 0, warnings: 0, issues: [] };
const tables = { process: processDefinition, forward: forwardDefinition };
const requests = [], errors = [];
let owned = false, folderInvalid = false;
const folder = await mkdtemp(join(tmpdir(), "protocol-folder-ui-"));
await writeFile(join(folder, "project.json"), JSON.stringify({ key: "dc-ups", name: "DC-UPS", topology: config }));
const lock = () => ({ locked: owned, owned, owner: owned ? user : null, expires_at: owned ? new Date(Date.now() + 120_000).toISOString() : null, lease_seconds: 120, permissions });
const server = await createServer({ root, logLevel: "error", server: { host: "127.0.0.1", port: 0 } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ baseURL: `http://127.0.0.1:${server.httpServer.address().port}`, viewport: { width: 1440, height: 1000 } });
  page.on("pageerror", error => errors.push(error.message));
  page.on("dialog", dialog => dialog.accept());
  await page.route("**/api/**", async route => {
    const request = route.request(), path = new URL(request.url()).pathname, method = request.method();
    const ok = json => route.fulfill({ json });
    if (method !== "GET") requests.push({ path, method, body: request.headers()["content-type"]?.includes("application/json") ? request.postDataJSON() : null });
    if (path === "/api/auth/me") return ok(user);
    if (path === "/api/projects") return ok([project]);
    if (path.endsWith("/permissions")) return ok(permissions);
    if (path.endsWith("/overview")) return ok({ project, validation, has_configuration: true });
    if (path.endsWith("/topology")) return ok(graph);
    if (path.includes("/edit-lock")) {
      if (path.endsWith("/acquire")) owned = true;
      if (path.endsWith("/release")) owned = false;
      return ok(lock());
    }
    if (path.endsWith("/point-tables/schema")) return ok({ boards: { DSP: tables }, workspace: { boards: { DSP: { tables: ["process", "forward"] } } } });
    const tableMatch = path.match(/^\/api\/projects\/1\/boards\/DSP\/point-tables\/(process|forward)$/);
    if (tableMatch) return ok({ revision: 1, board_key: "DSP", kind: tableMatch[1], storage: "native", definition: tables[tableMatch[1]], rows: tableMatch[1] === "process" ? [{ ...point, data_type: "U16", group_name: "DSP 内部数据", edit_values: point, forward_count: 0 }] : [], options: { native_groups: board.point_groups, process_points: [point], endpoints: board.point_endpoints } });
    if (path.endsWith("/configuration/source")) return ok({ key: "dc-ups", sha256: "a".repeat(64), config });
    if (path.endsWith("/changes/preview")) return ok({ id: 9, allowed: true, errors: [], impact: { count: 0, changes: [], affected_types: [board] } });
    if (path.endsWith("/members")) return method === "GET" ? ok([{ id: 2, username: "engineer", display_name: "工程师", active: true, role: "engineer", edit_scope: "scoped", grants: [] }]) : ok({});
    if (path === "/api/users") return ok([user, { id: 2, username: "engineer", display_name: "工程师", active: true }]);
    if (path === "/api/sql/definitions") return ok({ relations: ["process_points", "transmit_points", "point_history"], examples: [], sql: "SELECT p.*, t.address FROM process_points p LEFT JOIN transmit_points t ON t.process_point_id = p.id;" });
    if (path.endsWith("/sql")) return ok({ rows: [point], elapsed_ms: 1, truncated: false });
    if (path.endsWith("/releases")) return ok([]);
    if (path.endsWith("/generate")) return ok({ revision: 1, blocked: false, validation, files: { "board_types/DSP/process.json": JSON.stringify([point]), "board_types/DSP/UPP_SERVICE.xml": "<UPP />" } });
    if (path.endsWith("/audit")) return ok([{ id: 1, action: "point.update", display_name: user.display_name, entity: "process_points", created_at: "2026-10-19T00:00:00Z", before_data: { name: "原名称" }, after_data: point }]);
    if (path === "/api/project-folders/preview") {
      if (folderInvalid) return route.fulfill({ status: 400, json: { error: "项目配置校验失败", errors: [{ entity: "process_points", name: point.name, message: "点表分组不存在" }] } });
      const replace = request.postDataBuffer().toString("utf8").includes("project.dump");
      return ok({ token: "folder-preview", key: "dc-ups", name: "DC-UPS", existing_project_id: 1, revision: 1, replace_data: replace, files: ["project.json", ...(replace ? ["project.dump"] : [])] });
    }
    if (path === "/api/project-folders/commit") return route.fulfill({ status: 409, json: { error: "项目已被其他成员更新，请重新检查" } });
    errors.push(`Unexpected ${method} ${path}`);
    return route.fulfill({ status: 500, json: { error: `Unexpected ${method} ${path}` } });
  });
  await page.goto("/");
  const nav = page.getByRole("navigation", { name: "项目与板卡导航" });
  await expect(page.getByLabel("当前项目").locator("option:checked")).toHaveText("DC-UPS");
  await expect(page.getByRole("group", { name: "项目板卡类型协议拓扑" })).toBeVisible();
  await page.getByRole("button", { name: "查看 DSP 板卡内部信息", exact: true }).click();
  await expect(page.locator(".point-table tbody tr")).toHaveCount(1);
  await expect(page.getByRole("button", { name: "新建DSP内部数据", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "开始编辑", exact: true }).click();
  await expect(page.getByRole("button", { name: "新建DSP内部数据", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "选择 UPM 板卡", exact: true }).click();
  await expect(page.getByText("此板卡点表暂未启用", { exact: true })).toBeVisible();
  await expect(page.locator(".point-table")).toHaveCount(0);
  await nav.getByRole("button", { name: "项目设置", exact: true }).click();
  await expect(page.getByRole("tab", { name: /板卡模板|共享协议|共享数据/ })).toHaveCount(0);
  await page.getByRole("button", { name: "查看与导入项目配置", exact: true }).click();
  await expect(page.getByLabel("项目拓扑内容")).toHaveAttribute("readonly", "");
  await page.getByRole("button", { name: "检查项目配置", exact: true }).click();
  await expect(page.locator("dialog")).toContainText("配置检查通过");
  assert.equal(requests.at(-1).body.entity, "project_config");
  assert.deepEqual(requests.at(-1).body.values, config);
  await page.locator("dialog").getByRole("button", { name: "关闭", exact: true }).last().click();
  await page.getByRole("button", { name: "导入项目文件夹", exact: true }).click();
  const folderDialog = page.locator("dialog"), picker = page.getByLabel("选择项目文件夹", { exact: true });
  await picker.setInputFiles(folder);
  await expect(folderDialog).toContainText("保留当前数据库中的数据");
  await expect(folderDialog.getByRole("button", { name: "覆盖项目配置，保留点表数据", exact: true })).toBeEnabled();
  await writeFile(join(folder, "project.dump"), "Browser fixture; never restored");
  await picker.setInputFiles(folder);
  await expect(folderDialog).toContainText("使用项目 Dump 中的数据");
  await folderDialog.getByRole("button", { name: "覆盖项目配置与点表数据", exact: true }).click();
  await expect(folderDialog.locator(".notice[role=alert]")).toContainText("项目已被其他成员更新");
  await expect(folderDialog.getByRole("button", { name: /^覆盖项目配置/ })).toHaveCount(0);
  folderInvalid = true;
  await picker.setInputFiles(folder);
  await expect(folderDialog.getByLabel("导入校验详情")).toContainText("process_points / 母线电压：点表分组不存在");
  await folderDialog.getByRole("button", { name: "取消", exact: true }).click();
  await nav.getByRole("button", { name: "成员与权限", exact: true }).click();
  await page.getByRole("button", { name: /^工程师的编辑范围：/ }).click();
  const memberDialog = page.locator("dialog");
  await expect(memberDialog).toContainText("DSP 功率板");
  await expect(memberDialog).toContainText("UPP 对外接口");
  await memberDialog.getByText("内部点表", { exact: true }).locator("xpath=ancestor::label").getByRole("checkbox").check();
  await memberDialog.getByText("UPP 对外接口", { exact: true }).locator("xpath=ancestor::label").getByRole("checkbox").check();
  await memberDialog.getByRole("button", { name: "保存编辑范围", exact: true }).click();
  const memberSave = requests.findLast(request => request.method === "PUT" && request.path.endsWith("/members"));
  assert.deepEqual(memberSave.body.grants, [{ board_key: "DSP", scope: "internal" }, { board_key: "DSP", scope: "protocol", endpoint_key: "UPP_SERVICE" }]);
  await nav.getByRole("button", { name: "SQL 工作台", exact: true }).click();
  await expect(page.getByLabel("SQL 查询编辑器")).toHaveValue(/process_points/);
  await expect(page.locator(".sql-explorer")).toContainText("point_history");
  await page.getByRole("button", { name: "运行查询", exact: true }).click();
  await expect(page.locator(".sql-results")).toContainText("母线电压");
  await nav.getByRole("button", { name: "代码与版本", exact: true }).click();
  await page.getByRole("button", { name: "生成预览", exact: true }).click();
  await expect(page.locator(".code-tabs")).toContainText("board_types/DSP/process.json");
  await nav.getByRole("button", { name: "操作记录", exact: true }).click();
  await page.getByRole("button", { name: "查看变更", exact: true }).click();
  await expect(page.locator("dialog")).toContainText("原名称");
  await expect(page.locator("dialog")).toContainText("母线电压");
  await page.locator("dialog").getByRole("button", { name: "关闭", exact: true }).last().click();
  assert.deepEqual(errors, []);
  console.log("PASS: JSON-only topology/navigation, disabled UPM points, edit lease, read-only project config, folder import scope/conflicts, string-key member grants, SQL, release preview and audit");
} finally {
  await browser?.close();
  await server.close();
  await rm(folder, { recursive: true, force: true });
}
